def classify_message(text: str) -> Optional[Tuple[str, Dict[str, Any]]]:
    """
    Scans text against all 10 verticals.
    Returns (category_id, category_config) of the best match, or None.
    """
    if not text or len(text.strip()) < 10:
        return None

    clean_text = text.lower()

    for cat_id, cfg in CATEGORIES.items():
        has_negative = any(re.search(neg, clean_text) for neg in cfg["negatives"])
        if has_negative:
            continue

        has_core = any(re.search(trig, clean_text) for trig in cfg["triggers"])
        if not has_core:
            continue

        has_intent = any(re.search(ind, clean_text) for ind in cfg["intent_keywords"]) or '?' in text
        if has_intent or len(cfg["intent_keywords"]) == 0:
            return cat_id, cfg

    return None
